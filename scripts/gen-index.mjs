// Generates src/<dir>/index.generated.ts for every auto-discovered directory.
// Each module in those directories default-exports one definition (tool, endpoint, hook or undo handler);
// adding a file is all it takes to register it, so parallel branches don't edit a shared list.
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// dir → [exported type, module the type comes from]
const DIRS = {
  tools: ["ToolDef", "../registry/types"],
  endpoints: ["EndpointDef", "../registry/types"],
  hooks: ["LifecycleHook", "../registry/types"],
  undo: ["UndoHandler", "../changes/types"],
};

for (const [dir, [type, from]] of Object.entries(DIRS)) {
  const abs = join(root, "src", dir);
  mkdirSync(abs, { recursive: true });
  const files = readdirSync(abs)
    .filter((f) => f.endsWith(".ts") && !f.startsWith("_") && !f.startsWith("index.") && !f.endsWith(".d.ts"))
    .sort();
  const lines = [
    "// GENERATED by scripts/gen-index.mjs. Do not edit; add a file to this directory instead.",
    `import type { ${type} } from "${from}";`,
    ...files.map((f, i) => `import m${i} from "./${f.slice(0, -3)}";`),
    "",
    `const all: ${type}[] = [${files.map((_, i) => `m${i}`).join(", ")}];`,
    "export default all;",
    "",
  ];
  const out = join(abs, "index.generated.ts");
  const text = lines.join("\n");
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);
}
